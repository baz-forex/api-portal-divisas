package com.baz.divisas.api.tef.parametria.dto;

/**
 * The Class Parametro.
 */
public class Parametro {

	
	/** The id. */
	private String id;
	
	/** The parametro. */
	private String parametro;
	
	/** The descripcion. */
	private String descripcion;
	
	/** The sucursales asignadas. */
	private int sucursalesAsignadas;
	
	/**
	 * Gets the id.
	 *
	 * @return the id
	 */
	public String getId() {
		return id;
	}
	
	/**
	 * Sets the id.
	 *
	 * @param id the new id
	 */
	public void setId(String id) {
		this.id = id;
	}
	
	/**
	 * Gets the parametro.
	 *
	 * @return the parametro
	 */
	public String getParametro() {
		return parametro;
	}
	
	/**
	 * Sets the parametro.
	 *
	 * @param parametro the new parametro
	 */
	public void setParametro(String parametro) {
		this.parametro = parametro;
	}
	
	/**
	 * Gets the descripcion.
	 *
	 * @return the descripcion
	 */
	public String getDescripcion() {
		return descripcion;
	}
	
	/**
	 * Sets the descripcion.
	 *
	 * @param descripcion the new descripcion
	 */
	public void setDescripcion(String descripcion) {
		this.descripcion = descripcion;
	}
	
	/**
	 * Gets the sucursales asignadas.
	 *
	 * @return the sucursales asignadas
	 */
	public int getSucursalesAsignadas() {
		return sucursalesAsignadas;
	}
	
	/**
	 * Sets the sucursales asignadas.
	 *
	 * @param sucursalesAsignadas the new sucursales asignadas
	 */
	public void setSucursalesAsignadas(int sucursalesAsignadas) {
		this.sucursalesAsignadas = sucursalesAsignadas;
	}
	
	
}
