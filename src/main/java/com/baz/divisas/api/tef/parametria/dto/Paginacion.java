package com.baz.divisas.api.tef.parametria.dto;

/**
 * The Class Paginacion.
 */
public class Paginacion {

	/** The pagina. */
	private int pagina;
	
	/** The registros pagina. */
	private int registrosPagina;
	
	/** The total paginas. */
	private int totalPaginas;
	
	/** The total registros. */
	private int totalRegistros;
	
	/**
	 * Gets the pagina.
	 *
	 * @return the pagina
	 */
	public int getPagina() {
		return pagina;
	}
	
	/**
	 * Sets the pagina.
	 *
	 * @param pagina the new pagina
	 */
	public void setPagina(int pagina) {
		this.pagina = pagina;
	}
	
	/**
	 * Gets the registros pagina.
	 *
	 * @return the registros pagina
	 */
	public int getRegistrosPagina() {
		return registrosPagina;
	}
	
	/**
	 * Sets the registros pagina.
	 *
	 * @param registrosPagina the new registros pagina
	 */
	public void setRegistrosPagina(int registrosPagina) {
		this.registrosPagina = registrosPagina;
	}
	
	/**
	 * Gets the total paginas.
	 *
	 * @return the total paginas
	 */
	public int getTotalPaginas() {
		return totalPaginas;
	}
	
	/**
	 * Sets the total paginas.
	 *
	 * @param totalPaginas the new total paginas
	 */
	public void setTotalPaginas(int totalPaginas) {
		this.totalPaginas = totalPaginas;
	}
	
	/**
	 * Gets the total registros.
	 *
	 * @return the total registros
	 */
	public int getTotalRegistros() {
		return totalRegistros;
	}
	
	/**
	 * Sets the total registros.
	 *
	 * @param totalRegistros the new total registros
	 */
	public void setTotalRegistros(int totalRegistros) {
		this.totalRegistros = totalRegistros;
	}
	
	
}
