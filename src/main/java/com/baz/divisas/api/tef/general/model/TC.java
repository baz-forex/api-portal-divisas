package com.baz.divisas.api.tef.general.model;

/**
 * The Class TC.
 */
public class TC {

	/** The compra. */
	private double compra;
	
	/** The venta. */
	private double venta;
	
	/**
	 * Instantiates a new tc.
	 */
	public TC () {
		super();
	}

	/**
	 * Gets the compra.
	 *
	 * @return the compra
	 */
	public double getCompra() {
		return compra;
	}

	/**
	 * Sets the compra.
	 *
	 * @param compra the new compra
	 */
	public void setCompra(double compra) {
		this.compra = compra;
	}

	/**
	 * Gets the venta.
	 *
	 * @return the venta
	 */
	public double getVenta() {
		return venta;
	}

	/**
	 * Sets the venta.
	 *
	 * @param venta the new venta
	 */
	public void setVenta(double venta) {
		this.venta = venta;
	}
	
	
}
