package com.baz.divisas.api.core.beneficios.model;

/**
 * @author B86960
 *
 */
public class BeanMensajeDetallado {
	private String texto;
	private String negritas;
	private String tamanio;
	/**
	 * Constructor
	 */
	public BeanMensajeDetallado() {
		super();
	}
	/**
	 * @return the texto
	 */
	public String getTexto() {
		return texto;
	}
	/**
	 * @param texto the texto to set
	 */
	public void setTexto(String texto) {
		this.texto = texto;
	}
	/**
	 * @return the negritas
	 */
	public String getNegritas() {
		return negritas;
	}
	/**
	 * @param negritas the negritas to set
	 */
	public void setNegritas(String negritas) {
		this.negritas = negritas;
	}
	/**
	 * @return the tamanio
	 */
	public String getTamanio() {
		return tamanio;
	}
	/**
	 * @param tamanio the tamanio to set
	 */
	public void setTamanio(String tamanio) {
		this.tamanio = tamanio;
	}
	
}
